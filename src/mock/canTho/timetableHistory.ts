import {
    TIMETABLE_SCENARIOS,
    plannedTimetables,
} from "./timetablePlan";

import type {
    TimetableHistoryEntry,
} from "../common/types";


const findEntry = (
    id: string,
) => plannedTimetables.find((item) => item.id === id);

const snapshot = (
    id: string,
    overrides: Partial<TimetableHistoryEntry["after"]> = {},
) => {
    const entry = findEntry(id);

    if (!entry) {
        return undefined;
    }

    return {
        classId: entry.classId,
        teacherId: entry.teacherId,
        subjectId: entry.subjectId,
        roomId: entry.roomId,
        dayOfWeek: entry.dayOfWeek,
        period: entry.period,
        week: entry.week,
        status: entry.status,
        version: entry.version,
        ...overrides,
    };
};

